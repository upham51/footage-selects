// Writes THIRD_PARTY_LICENSES: everything that ships inside the app, with its
// license, and a check for licenses that could force the app's own code to be
// published.
//
//   node scripts/third-party-licenses.mjs           rewrite the file
//   node scripts/third-party-licenses.mjs --check   fail if the file is out of date
//                                                   or a shipped library has a risky license
//
// Rust libraries are read from Cargo for the shipping targets (macOS on
// Apple silicon and Intel, and 64-bit Windows), following only the libraries compiled
// into the app, not build tools or test helpers.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const TARGETS = ["aarch64-apple-darwin", "x86_64-apple-darwin", "x86_64-pc-windows-msvc"];
const ROOT_PACKAGE = "footage-selects";

// Licenses that never oblige the app to publish its own code.
const PERMISSIVE = new Set([
  "MIT", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "ISC", "Zlib", "Unicode-3.0",
  "Unicode-DFS-2016", "0BSD", "BSL-1.0", "CC0-1.0", "Unlicense", "MIT-0", "Apache-2.0 WITH LLVM-exception",
  "BSD-1-Clause", "OFL-1.1", "CDLA-Permissive-2.0", "bzip2-1.0.6",
]);
// File-level copyleft: changes to those files must be shared, the app's own code is unaffected.
const WEAK_FILE_LEVEL = new Set(["MPL-2.0"]);

/** Decide whether an SPDX expression can be used without publishing our code. */
export function classify(expr) {
  if (!expr) return "unknown";
  const alternatives = expr.replace(/[()]/g, "").split(/\s+OR\s+|\//).map((s) => s.trim());
  const ok = (alt) => alt.split(/\s+AND\s+/).every((p) => PERMISSIVE.has(p.trim()));
  if (alternatives.some(ok)) return "permissive";
  const weak = (alt) => alt.split(/\s+AND\s+/).every((p) => PERMISSIVE.has(p.trim()) || WEAK_FILE_LEVEL.has(p.trim()));
  if (alternatives.some(weak)) return "file-level";
  return "review";
}

function rustCrates() {
  const seen = new Map();
  for (const target of TARGETS) {
    const meta = JSON.parse(
      execFileSync("cargo", ["metadata", "--format-version", "1", "--locked", "--filter-platform", target], {
        maxBuffer: 256 * 1024 * 1024,
        encoding: "utf8",
      }),
    );
    const pkgs = new Map(meta.packages.map((p) => [p.id, p]));
    const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
    const root = meta.packages.find((p) => p.name === ROOT_PACKAGE);
    const stack = [root.id];
    const visited = new Set();
    while (stack.length) {
      const id = stack.pop();
      if (visited.has(id)) continue;
      visited.add(id);
      const p = pkgs.get(id);
      if (p.source) seen.set(`${p.name} ${p.version}`, { name: p.name, version: p.version, license: p.license || (p.license_file ? `see ${p.license_file}` : ""), repo: p.repository || "" });
      for (const dep of nodes.get(id).deps) {
        if (dep.dep_kinds.some((k) => k.kind === null)) stack.push(dep.pkg);
      }
    }
  }
  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

function render(crates) {
  const productName = JSON.parse(readFileSync("src-tauri/tauri.conf.json", "utf8")).productName;
  const review = crates.filter((c) => classify(c.license) === "review" || classify(c.license) === "unknown");
  const fileLevel = crates.filter((c) => classify(c.license) === "file-level");
  const lines = [];
  lines.push(`THIRD PARTY LICENSES`);
  lines.push(``);
  lines.push(`${productName} includes the software and fonts listed below. Each keeps its own license.`);
  lines.push(`This file is generated by scripts/third-party-licenses.mjs; the Rust library list is regenerated from Cargo.`);
  lines.push(``);
  lines.push(`SUMMARY: DOES ANYTHING FORCE THE APP'S OWN CODE TO BE OPEN SOURCED?`);
  lines.push(``);
  lines.push(`No, as long as ffmpeg stays a separate program built under the LGPL (see 1 below).`);
  lines.push(``);
  lines.push(`1. FFmpeg is LGPL 2.1 or later. It ships as two separate programs (ffmpeg and ffprobe) that the`);
  lines.push(`   app starts and talks to through pipes; the app does not link to FFmpeg's code. That keeps the`);
  lines.push(`   app's own code free of LGPL obligations. What the LGPL does require, and what each release`);
  lines.push(`   must keep doing: say that FFmpeg is included and under which license (this file and the README),`);
  lines.push(`   include the license text (below), and point to the exact source code used (BUILD_INFO.txt from`);
  lines.push(`   scripts/build-ffmpeg.sh names the source release, its checksum and the configure line).`);
  lines.push(`   The build stops if anything GPL, LGPL version 3 or non-free is switched on. Never ship a GPL`);
  lines.push(`   ffmpeg build (for example one that includes x264 or x265): that would put the whole app under the GPL.`);
  lines.push(`2. Rust libraries compiled into the app: ${crates.length} libraries, all under permissive licenses` + (fileLevel.length ? ` except ${fileLevel.length} under the Mozilla Public License 2.0, which only asks that changes to those libraries' own files be shared. The app's own code is unaffected.` : "."));
  if (review.length) {
    lines.push(`3. NEEDS REVIEW: ${review.map((c) => `${c.name} ${c.version} (${c.license || "no license listed"})`).join(", ")}.`);
  } else {
    lines.push(`3. Nothing needs review: no GPL, AGPL, LGPL or unlicensed Rust library is compiled into the app.`);
  }
  lines.push(`4. Fonts (Inter, Inter Tight, Averia Serif Libre) are under the SIL Open Font License 1.1, which allows`);
  lines.push(`   bundling them in any app. The license text is in ui/fonts/LICENSE.txt and ships with the app.`);
  lines.push(`5. Not bundled: the system web view (WebKit on macOS, Microsoft Edge WebView2 on Windows) belongs to`);
  lines.push(`   the operating system. The Tauri command line tool is used only to build the installers.`);
  lines.push(``);
  lines.push(``);
  lines.push(`FFMPEG`);
  lines.push(``);
  lines.push(`FFmpeg 9.0.2, https://ffmpeg.org`);
  lines.push(`License: GNU Lesser General Public License, version 2.1 or later (LGPL-2.1-or-later)`);
  lines.push(`Source: https://ffmpeg.org/releases/ffmpeg-9.0.2.tar.xz`);
  lines.push(`Built by scripts/build-ffmpeg.sh with no external libraries except the operating system's own`);
  lines.push(`video decoding (VideoToolbox on macOS, Direct3D 11 and DXVA2 on Windows) and zlib.`);
  lines.push(``);
  lines.push(`zlib 1.3.2 (statically linked into the Windows ffmpeg; macOS uses the system copy), https://zlib.net`);
  lines.push(`License: zlib license (Zlib)`);
  lines.push(``);
  lines.push(``);
  lines.push(`FONTS`);
  lines.push(``);
  lines.push(`Inter and Inter Tight, by Rasmus Andersson: SIL Open Font License 1.1 (OFL-1.1)`);
  lines.push(`Averia Serif Libre, by Dan Sayers: SIL Open Font License 1.1 (OFL-1.1)`);
  lines.push(``);
  lines.push(``);
  lines.push(`RUST LIBRARIES COMPILED INTO THE APP`);
  lines.push(``);
  for (const c of crates) lines.push(`${c.name} ${c.version}: ${c.license || "no license listed"}${c.repo ? `  ${c.repo}` : ""}`);
  lines.push(``);
  lines.push(``);
  lines.push(`LICENSE TEXTS`);
  lines.push(``);
  lines.push(`The full texts of the licenses above are published at https://spdx.org/licenses/ under each`);
  lines.push(`identifier. The GNU LGPL 2.1 text follows, because FFmpeg's license requires it to accompany the program.`);
  lines.push(``);
  lines.push(readFileSync("scripts/licenses/LGPL-2.1.txt", "utf8").trimEnd());
  lines.push(``);
  return { text: lines.join("\n"), review };
}

if (process.argv[1] && process.argv[1].endsWith("third-party-licenses.mjs")) {
  const { text, review } = render(rustCrates());
  if (process.argv.includes("--check")) {
    const current = existsSync("THIRD_PARTY_LICENSES") ? readFileSync("THIRD_PARTY_LICENSES", "utf8") : "";
    if (review.length) {
      console.error(`These libraries need a license review before shipping: ${review.map((c) => `${c.name} (${c.license || "none"})`).join(", ")}`);
      process.exit(1);
    }
    if (current !== text) {
      console.error("THIRD_PARTY_LICENSES is out of date. Run: node scripts/third-party-licenses.mjs");
      process.exit(1);
    }
    console.log("THIRD_PARTY_LICENSES is current and nothing needs review.");
  } else {
    writeFileSync("THIRD_PARTY_LICENSES", text);
    console.log(`Wrote THIRD_PARTY_LICENSES. Needs review: ${review.length ? review.map((c) => c.name).join(", ") : "nothing"}.`);
  }
}
